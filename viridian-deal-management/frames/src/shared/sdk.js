var _bodyNodes = [];

function hasLoadingKind(arr) {
  for (var i = 0; i < arr.length; i++) {
    var item = arr[i];
    if (Array.isArray(item)) { if (hasLoadingKind(item)) return true; }
    else if (item && typeof item === 'object' && item.kind === 'loading') return true;
  }
  return false;
}

function isReady(data) {
  if (!data || !data.labels || !data.labels.columns.length) return false;
  return !hasLoadingKind(data.labels.rows) &&
         !hasLoadingKind(data.labels.columns) &&
         !hasLoadingKind(data.cells);
}

// Last string entry of a label path is the display name.
function labelName(path) {
  if (typeof path === 'string') return path;
  if (!Array.isArray(path)) return '';
  for (var i = path.length - 1; i >= 0; i--) {
    if (typeof path[i] === 'string') return path[i];
  }
  return '';
}

function labelAt(path, level) {
  if (!Array.isArray(path)) return labelName(path);
  var v = path[level];
  return typeof v === 'string' ? v : '';
}

function cell(data, c, r) {
  if (!data || !data.cells || !data.cells[c]) return null;
  var v = data.cells[c][r];
  if (v && typeof v === 'object') return null;
  return v;
}

// Index a data source's columns so pages can read by metric display name
// regardless of position. A data source may label its columns with the binding
// alias rather than the metric's display name, so register both: COL_ALIAS is
// generated by build.py and maps alias -> display name.
function columnIndex(data) {
  var idx = {};
  if (!data || !data.labels) return idx;
  for (var c = 0; c < data.labels.columns.length; c++) {
    var raw = labelName(data.labels.columns[c]);
    idx[raw] = c;
    if (typeof COL_ALIAS !== 'undefined' && COL_ALIAS[raw] !== undefined) {
      idx[COL_ALIAS[raw]] = c;
    }
  }
  return idx;
}

// Same idea for a data source whose single row is a metric (the scalar and
// import-summary sources): find a row by display name or by binding alias.
function rowByName(data, name) {
  if (!data || !data.labels) return -1;
  for (var r = 0; r < data.labels.rows.length; r++) {
    var raw = labelName(data.labels.rows[r]);
    if (raw === name) return r;
    if (typeof COL_ALIAS !== 'undefined' && COL_ALIAS[raw] === name) return r;
  }
  return -1;
}

// The data source hands back row-major data with no column labels:
//   { rows: [ { labels: [...], values: [...] } ], rowOffset, totalRowCount }
// Values arrive in the order the data source declares them, so DS_COLUMNS
// (generated by gen_bindings.py, injected by build.py) is what names them.
// Everything above this line still reads the older column-major grid, so the
// payload is adapted once here rather than in six pages.
function adaptGrid(dsName, raw) {
  var cols = (typeof DS_COLUMNS !== 'undefined' && DS_COLUMNS[dsName]) || [];
  var rows = (raw && raw.rows) || [];
  var grid = {
    labels: { rows: [], columns: cols.slice() },
    cells: [],
    rowOffset: (raw && raw.rowOffset) || 0,
    totalRowCount: (raw && raw.totalRowCount) || rows.length
  };
  grid.truncated = grid.totalRowCount > rows.length;
  var c, r;
  for (c = 0; c < cols.length; c++) grid.cells.push([]);
  for (r = 0; r < rows.length; r++) {
    var lab = rows[r].labels || [];
    grid.labels.rows.push(lab.length === 1 ? lab[0] : lab.slice());
    var vals = rows[r].values || [];
    for (c = 0; c < cols.length; c++) {
      grid.cells[c].push(vals[c] === undefined ? null : vals[c]);
    }
  }
  return grid;
}

// One object per row of a single-label data source, keyed the way the pages
// used to read list items: the row label under keyName, then every column.
function rowsAsItems(grid, keyName) {
  var out = [];
  if (!grid) return out;
  var cols = grid.labels.columns;
  for (var r = 0; r < grid.labels.rows.length; r++) {
    var o = {};
    o[keyName] = labelAt(grid.labels.rows[r], 0) || labelName(grid.labels.rows[r]);
    for (var c = 0; c < cols.length; c++) o[cols[c]] = cell(grid, c, r);
    out.push(o);
  }
  return out;
}

// Reference lists come back through their property data source, so the labels
// are the item names and the columns are the properties.
function listFromProps(grid) { return rowsAsItems(grid, 'Name'); }

function listFromNames(names) {
  var out = [];
  for (var i = 0; i < (names || []).length; i++) out.push({ Name: names[i] });
  return out;
}

function sortByOrder(arr) {
  arr.sort(function (a, b) {
    var ao = typeof a.Order === 'number' ? a.Order : 9999;
    var bo = typeof b.Order === 'number' ? b.Order : 9999;
    if (ao !== bo) return ao - bo;
    return String(a.Name).localeCompare(String(b.Name));
  });
  return arr;
}

// Reference lists for the dropdowns. Where the list has properties a page
// needs - Stage.Order, Use Case.CRM Codes - they come from its property data
// source, which also supplies the names; otherwise the item names are enough.
// spec: [{ alias: 'stage', ds: 'vwStageProps' }, { alias: 'salesMotion' }]
function subscribeRefLists(lists, spec, redraw, fail) {
  for (var i = 0; i < spec.length; i++) {
    (function (s) {
      if (s.ds) {
        subscribeView(s.ds, function (d) {
          lists[s.alias] = sortByOrder(listFromProps(d));
          redraw();
        }, fail);
      } else {
        subscribeList(s.alias, function (items) {
          lists[s.alias] = items;
          redraw();
        }, fail);
      }
    })(spec[i]);
  }
}

// A data source carries one value type, so each logical source is stored as
// several per-type parts (D18). They share their labels, so the parts are
// joined back into one grid on the row labels before a page ever sees them.
function labelKey(lab) {
  return typeof lab === 'string' ? lab : (lab || []).join('\u0001');
}

function mergeParts(parts, store) {
  var out = { labels: { rows: [], columns: [] }, cells: [], rowOffset: 0,
              totalRowCount: 0, truncated: false };
  var index = {}, p, r, c, g;

  for (p = 0; p < parts.length; p++) {
    g = store[parts[p]];
    if (!g) continue;
    out.truncated = out.truncated || !!g.truncated;
    if (g.totalRowCount > out.totalRowCount) out.totalRowCount = g.totalRowCount;
    for (r = 0; r < g.labels.rows.length; r++) {
      var k = labelKey(g.labels.rows[r]);
      if (index[k] === undefined) {
        index[k] = out.labels.rows.length;
        out.labels.rows.push(g.labels.rows[r]);
      }
    }
  }

  for (p = 0; p < parts.length; p++) {
    g = store[parts[p]];
    if (!g) continue;
    for (c = 0; c < g.labels.columns.length; c++) {
      var col = [];
      for (var n = 0; n < out.labels.rows.length; n++) col.push(null);
      for (r = 0; r < g.labels.rows.length; r++) {
        col[index[labelKey(g.labels.rows[r])]] = cell(g, c, r);
      }
      out.labels.columns.push(g.labels.columns[c]);
      out.cells.push(col);
    }
  }
  return out;
}

// Every source is fetched, not held: the subscription is dropped as soon as it
// has answered, because Pigment caps how many a Frame may hold at once (D23).
// Where the page writes, the source is re-fetched after the write instead.
// ---- optimistic overlay ---------------------------------------------------
// Pigment recalculates asynchronously, so the re-read that follows a write can
// still be carrying the value from before it. The pages keep no record of what
// they just wrote, so they render that stale value straight back over the edit:
// it says "Saved", then it reverts. Every write now parks what it wrote, and
// every grid is overlaid with whatever is still outstanding before a page sees
// it. An entry retires the moment the server agrees on every column it touched,
// or after PENDING_TTL if the server never does - so a write Pigment silently
// refused cannot pin a wrong number on screen for ever.

var PENDING_TTL = 120000;
var _pending = [];

// match: label values that must all appear in a row's label path.
// cols:  display column name -> the value the write should produce.
function notePending(match, cols) {
  var key = match.join('\u0001') + '|';
  var names = [], n;
  for (n in cols) if (Object.prototype.hasOwnProperty.call(cols, n)) names.push(n);
  names.sort();
  key += names.join(',');

  var entry = { key: key, match: match, cols: cols, ok: {}, at: Date.now() };
  for (var i = _pending.length - 1; i >= 0; i--) {
    if (_pending[i].key === key) _pending.splice(i, 1);
  }
  _pending.push(entry);
  return entry;
}

function dropPending(entry) {
  var i = _pending.indexOf(entry);
  if (i !== -1) _pending.splice(i, 1);
}

function rowMatches(labels, match) {
  for (var m = 0; m < match.length; m++) {
    var found = false;
    for (var l = 0; l < labels.length; l++) if (labels[l] === match[m]) { found = true; break; }
    if (!found) return false;
  }
  return true;
}

// Blank is blank however it arrives, and a float that survived a round trip is
// the same number it went out as.
function sameValue(a, b) {
  if (a === null || a === undefined || a === '') return b === null || b === undefined || b === '';
  if (b === null || b === undefined || b === '') return false;
  if (typeof a === 'number' && typeof b === 'number') return Math.abs(a - b) < 1e-9;
  return String(a) === String(b);
}

function applyPending(grid) {
  if (!_pending.length || !grid || !grid.labels) return grid;

  var cutoff = Date.now() - PENDING_TTL, live = [], i;
  for (i = 0; i < _pending.length; i++) if (_pending[i].at >= cutoff) live.push(_pending[i]);
  _pending = live;
  if (!live.length) return grid;

  var idx = columnIndex(grid);
  for (var r = 0; r < grid.labels.rows.length; r++) {
    var path = grid.labels.rows[r];
    var labels = typeof path === 'string' ? [path] : (path || []);
    for (var e = 0; e < live.length; e++) {
      var entry = live[e];
      if (!rowMatches(labels, entry.match)) continue;
      for (var name in entry.cols) {
        if (!Object.prototype.hasOwnProperty.call(entry.cols, name)) continue;
        var c = idx[name];
        if (c === undefined) continue;          // not a column of this source
        if (sameValue(cell(grid, c, r), entry.cols[name])) entry.ok[name] = true;
        else grid.cells[c][r] = entry.cols[name];
      }
    }
  }

  // Each column is released on its own as soon as the server agrees on it.
  // All-or-nothing would let one slow column pin the rest: a stage change also
  // stamps Closed On, and holding the stage hostage to that would hide the next
  // edit somebody else made.
  var keep = [];
  for (i = 0; i < live.length; i++) {
    var left = 0;
    for (var k in live[i].cols) {
      if (!Object.prototype.hasOwnProperty.call(live[i].cols, k)) continue;
      if (live[i].ok[k]) delete live[i].cols[k];
      else left++;
    }
    if (left) keep.push(live[i]);
  }
  _pending = keep;
  return grid;
}

var _views = [];

function fetchView(alias, onReady, onErr, scroll) {
  var parts = (typeof DS_PARTS !== 'undefined' && DS_PARTS[alias]) || [alias];
  var store = {}, arrived = 0;
  for (var i = 0; i < parts.length; i++) {
    (function (part) {
      subscribePart(part, function (grid) {
        if (!store[part]) arrived++;
        store[part] = grid;
        // Wait for every part, otherwise a page would render against half its
        // columns and then flicker as the rest land.
        if (arrived === parts.length) onReady(applyPending(mergeParts(parts, store)));
      }, onErr, scroll);
    })(parts[i]);
  }
}

function subscribeView(alias, onReady, onErr, pageDefs, scroll) {
  _views.push({ alias: alias, onReady: onReady, onErr: onErr, scroll: scroll });
  fetchView(alias, onReady, onErr, scroll);
  // Callers keep this to tell "already subscribed" from "not yet".
  return { alias: alias };
}

// Re-read whatever this page can change. Pigment recalculates after the write
// lands, so the read is held back a moment rather than racing it.
var refreshViews = null;

// A re-render replaces the whole content area, which throws away whatever is
// half-typed in another cell. So the re-read waits for the cursor to leave.
// The overlay above keeps the screen honest in the meantime; the cap stops a
// cursor parked in a field from deferring the read for ever.
var _refreshDeferrals = 0;

function isEditing() {
  var a = document.activeElement;
  if (!a || !a.tagName) return false;
  var tag = a.tagName.toUpperCase();
  if (tag !== 'INPUT' && tag !== 'TEXTAREA' && tag !== 'SELECT') return false;
  return a.type !== 'checkbox' && a.type !== 'button';
}

function _refreshViewsNow() {
  if (_refreshDeferrals < 20 && isEditing()) {
    _refreshDeferrals++;
    if (refreshViews) refreshViews();
    return;
  }
  _refreshDeferrals = 0;
  var live = (typeof DS_LIVE !== 'undefined' && DS_LIVE) || [];
  var done = {};
  for (var i = 0; i < _views.length; i++) {
    var v = _views[i];
    if (live.indexOf(v.alias) === -1 || done[v.alias]) continue;
    done[v.alias] = 1;
    fetchView(v.alias, v.onReady, v.onErr, v.scroll);
  }
}

// The host sizes the Frame with an AutoSizer, so a window resize event is not
// the only way the viewport changes. The skill calls for both; only the window
// listener was wired, which left the layout stale on a host-driven resize.
function onViewportResize(fn) {
  var debounced = debounce(fn, 120);
  on(window, 'resize', debounced);
  if (typeof ResizeObserver === 'function') {
    var ro = new ResizeObserver(debounced);
    ro.observe(document.documentElement);
    trackObserver(ro);
  }
}

// ---- self-diagnosis ------------------------------------------------------
// Pigment is not reachable from the build environment and the Frames sandbox
// gives no console, so a failure used to surface as one error message with no
// way to tell which of a page's ~20 sources caused it. Every part now records
// its own outcome, and if anything is still pending or has failed 8 seconds in,
// the page replaces itself with the whole picture rather than a single line.

var DIAG = { parts: {}, order: [], armed: false };

function diagNote(name, state, detail) {
  if (!DIAG.parts[name]) DIAG.order.push(name);
  DIAG.parts[name] = { state: state, detail: detail === undefined ? '' : String(detail) };
}

function diagCounts() {
  var c = { ok: 0, pending: 0, error: 0 };
  for (var i = 0; i < DIAG.order.length; i++) c[DIAG.parts[DIAG.order[i]].state]++;
  return c;
}

function diagHtml() {
  var c = diagCounts();
  var h = '<div style="padding:16px 24px;font:13px ' + FONT.body + ';color:' + T.bodyInk + ';">';
  h += '<div style="font:700 20px ' + FONT.display + ';color:' + T.ink + ';">Data source report</div>';
  h += '<div style="color:' + T.secondary + ';margin:4px 0 14px;">' +
    c.ok + ' returned data, ' + c.error + ' failed, ' + c.pending + ' never answered. ' +
    'SDK: ' + esc(SUB_DATA || 'none') + ' / ' + esc(SUB_ITEMS || 'none') + '.</div>';
  h += '<table style="border-collapse:collapse;font:12px ' + FONT.mono + ';">';
  for (var i = 0; i < DIAG.order.length; i++) {
    var name = DIAG.order[i], d = DIAG.parts[name];
    var colour = d.state === 'ok' ? T.green : (d.state === 'error' ? T.red : T.copperText);
    h += '<tr><td style="padding:3px 14px 3px 0;color:' + T.ink + ';white-space:nowrap;">' + esc(name) + '</td>' +
      '<td style="padding:3px 14px 3px 0;color:' + colour + ';font-weight:600;">' + d.state + '</td>' +
      '<td style="padding:3px 0;color:' + T.secondary + ';">' + esc(d.detail) + '</td></tr>';
  }
  h += '</table>';
  h += '<div style="margin-top:14px;color:' + T.muted + ';font:12px ' + FONT.body + ';">' +
    'Copy this table into the build session - it names every source Pigment rejected.</div>';
  h += '</div>';
  return h;
}

// Shown only when something is actually wrong, so a healthy page never sees it.
function diagArm() {
  if (DIAG.armed) return;
  DIAG.armed = true;
  var t = setTimeout(function () {
    var c = diagCounts();
    if (!c.error && !c.pending) return;
    var host = document.getElementById('app');
    if (host) host.innerHTML = diagHtml();
  }, 8000);
  _timers.push(t);
}

// ---- subscription budget -------------------------------------------------
// Pigment allows a Frame only about thirteen data sources at once - the
// fourteenth comes back "Too many active subscriptions for this resource" -
// and D18's split by value type turned seven logical sources into twenty-five
// parts. So subscriptions queue against a budget, and a source the page cannot
// write to hands its slot on as soon as it has answered once: it will not
// change underneath the page, so holding it open buys nothing (D23).

var SUB_BUDGET = 6;
var _slots = 0;
var _waiting = [];

function pumpSubs() {
  while (_slots < SUB_BUDGET && _waiting.length) {
    _slots++;
    _waiting.shift()();
  }
}

function freeSlot() {
  if (_slots > 0) _slots--;
  pumpSubs();
}

function subscribePart(alias, onReady, onErr, scroll) {
  diagNote(alias, 'pending', 'queued');
  diagArm();
  _waiting.push(function () { startPart(alias, onReady, onErr, scroll); });
  pumpSubs();
}

function startPart(alias, onReady, onErr, scroll) {
  var holder = { sub: null, released: false };
  function release() {
    if (holder.released) return;
    holder.released = true;
    stopSub(holder.sub);
    freeSlot();
  }
  diagNote(alias, 'pending', 'subscribed, no response yet');
  var opts = {
    onData: function (data) {
      var grid = adaptGrid(alias, data);
      if (!isReady(grid)) {
        diagNote(alias, 'pending', 'payload arrived but was still loading');
        return;
      }
      diagNote(alias, 'ok', grid.labels.rows.length + ' rows x ' +
               grid.labels.columns.length + ' cols' + (grid.truncated ? ', truncated' : ''));
      onReady(grid);
      release();
    },
    onError: function (err) {
      diagNote(alias, 'error', (err && err.message) ? err.message : String(err));
      release();
      if (onErr) onErr(err);
    },
    dynamicFilters: []
  };
  // 1,000 rows is the ceiling the SDK allows in one window. Sources return
  // only populated rows, so this covers the whole model many times over; a
  // source that did overflow reports it through grid.truncated.
  opts.scroll = scroll || { offset: 0, numberOfRows: 1000 };
  if (!SUB_DATA) {
    diagNote(alias, 'error', 'no data-source subscription on this build');
    freeSlot();
    if (onErr) onErr(new Error('This Pigment build has no data-source subscription. SDK methods: ' + sdkSurface()));
    return null;
  }
  try {
    holder.sub = SDK[SUB_DATA](alias, opts);
  } catch (e) {
    diagNote(alias, 'error', 'threw on subscribe: ' + (e && e.message ? e.message : e));
    freeSlot();
    if (onErr) onErr(new Error((e && e.message ? e.message : 'Subscription failed') + ' (' + SUB_DATA + ' "' + alias + '")'));
    return null;
  }
  if (holder.sub) _subs.push(holder.sub);
  // onData can fire before the call returns, so the handle may only now exist.
  if (holder.released) stopSub(holder.sub);
  return holder.sub;
}

function subscribeList(alias, onReady, onErr) {
  if (!SUB_ITEMS) {
    if (onErr) onErr(new Error('This Pigment build has no item subscription. SDK methods: ' + sdkSurface()));
    return null;
  }
  var sub;
  try {
    // Items are plain item names now, not objects: anything else a Frame shows
    // has to come from a data source over list properties (D17).
    diagNote('items:' + alias, 'pending', 'subscribed, no response yet');
    diagArm();
    sub = SDK[SUB_ITEMS](alias, {
      onData: function (d) {
        var names = (d && d.items) || [];
        diagNote('items:' + alias, 'ok', names.length + ' items');
        onReady(listFromNames(names), !!(d && d.partialResult));
      },
      onError: function (err) {
        diagNote('items:' + alias, 'error', (err && err.message) ? err.message : String(err));
        if (onErr) onErr(err);
      }
    });
  } catch (e) {
    if (onErr) onErr(new Error((e && e.message ? e.message : 'Subscription failed') + ' (' + SUB_ITEMS + ' "' + alias + '")'));
    return null;
  }
  if (sub) _subs.push(sub);
  return sub;
}

// A subscription may come back as an object with unsubscribe() or as the
// unsubscribe function itself; repaging may not be offered at all.
function stopSub(sub) {
  if (!sub) return;
  try {
    if (typeof sub === 'function') sub();
    else if (typeof sub.unsubscribe === 'function') sub.unsubscribe();
  } catch (e) {}
}

function debounce(fn, ms) {
  var t = null;
  function wrapped() {
    var args = arguments;
    if (t) clearTimeout(t);
    t = setTimeout(function () { t = null; fn.apply(null, args); }, ms);
    _timers.push(t);
  }
  return wrapped;
}

function on(target, type, handler) {
  target.addEventListener(type, handler);
  _listeners.push({ target: target, type: type, handler: handler });
}

function trackObserver(o) { _observers.push(o); return o; }
function trackBodyNode(n) { _bodyNodes.push(n); return n; }

function disposeAll() {
  for (var i = 0; i < _subs.length; i++) stopSub(_subs[i]);
  for (var j = 0; j < _timers.length; j++) clearTimeout(_timers[j]);
  for (var k = 0; k < _listeners.length; k++) {
    var L = _listeners[k];
    try { L.target.removeEventListener(L.type, L.handler); } catch (e) {}
  }
  for (var m = 0; m < _observers.length; m++) {
    try { _observers[m].disconnect(); } catch (e) {}
  }
  for (var n = 0; n < _bodyNodes.length; n++) {
    var el = _bodyNodes[n];
    if (el && el.parentNode) el.parentNode.removeChild(el);
  }
  _subs = []; _timers = []; _listeners = []; _observers = []; _bodyNodes = [];
}

// ---- writes -------------------------------------------------------------
// Each resolves to {ok:true} or {ok:false, message} so callers can revert the
// field and surface the SDK's own message rather than a generic failure.

// "Referencing properties by friendly name in addItem/editItem is no longer
// supported. Reference properties through their bindings instead." Pages still
// read and write in friendly names, which is what the model calls them; the
// translation to binding aliases happens here, once (D21).
function bindProps(listAlias, values) {
  var map = (typeof WRITE_PROPS !== 'undefined' && WRITE_PROPS[listAlias]) || {};
  var out = {}, unmapped = [];
  for (var key in values) {
    if (!Object.prototype.hasOwnProperty.call(values, key)) continue;
    if (map[key]) {
      out[map[key]] = values[key];
    } else {
      // Pass it through so the SDK's own message names it, and record the gap:
      // a property written but never bound is a generator bug, not a user one.
      unmapped.push(key);
      out[key] = values[key];
    }
  }
  if (unmapped.length) {
    diagNote('write:' + listAlias, 'error', 'no writable binding for ' + unmapped.join(', '));
  }
  return out;
}

// optimistic: columns to hold beyond the ones written, where a write moves a
// figure the page actually displays (an override feeding an effective value).
// Friendly property names are the grid's column names, so values serves as the
// default overlay.
function writeItem(listAlias, itemName, values, optimistic) {
  var entry = notePending([itemName], optimistic || values);
  return SDK.editItem(listAlias, itemName, bindProps(listAlias, values))
    .then(function () { toast('Saved'); if (refreshViews) refreshViews(); return { ok: true }; })
    .catch(function (e) {
      var msg = (e && e.message) ? e.message : 'Could not save';
      dropPending(entry);
      toast(msg, true);
      return { ok: false, message: msg };
    });
}

function createItem(listAlias, values) {
  return SDK.addItem(listAlias, bindProps(listAlias, values))
    .then(function () { if (refreshViews) refreshViews(); return { ok: true }; })
    .catch(function (e) {
      var msg = (e && e.message) ? e.message : 'Could not create';
      return { ok: false, message: msg };
    });
}

function writeValue(metricAlias, coords, value, optimistic) {
  var match = [], cols = {}, k;
  for (k in coords) if (Object.prototype.hasOwnProperty.call(coords, k)) match.push(coords[k]);
  cols[(typeof COL_ALIAS !== 'undefined' && COL_ALIAS[metricAlias]) || metricAlias] = value;
  if (optimistic) {
    for (k in optimistic) if (Object.prototype.hasOwnProperty.call(optimistic, k)) cols[k] = optimistic[k];
  }
  var entry = notePending(match, cols);

  return SDK.editValue(metricAlias, coords, value)
    .then(function () { toast('Saved'); if (refreshViews) refreshViews(); return { ok: true }; })
    .catch(function (e) {
      var msg = (e && e.message) ? e.message : 'Could not save';
      dropPending(entry);
      toast(msg, true);
      return { ok: false, message: msg };
    });
}

// debounce is declared below subscribeView, so the handle is bound once here:
// a burst of writes then costs one re-read rather than one each.
refreshViews = debounce(_refreshViewsNow, 500);
